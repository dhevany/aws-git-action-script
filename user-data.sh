
#!/bin/bash

# =========================================================
# UPDATE AMAZON LINUX 2023
# =========================================================

dnf update -y

# =========================================================
# INSTALL APACHE WEB SERVER
# =========================================================

dnf install -y httpd

# =========================================================
# START APACHE
# =========================================================

systemctl start httpd

# =========================================================
# ENABLE APACHE ON BOOT
# =========================================================

systemctl enable httpd

# =========================================================
# CREATE WEB PAGE
# =========================================================

echo "<h1>Welcome to Terraform DevOps Project</h1>" > /var/www/html/index.html
